// Write docs/parts.md from the shipped symbol and module libraries.
//
//   npm run docs:parts
//
// One table row per part type. Nothing here is typed by hand: the rows come from BUILTIN and
// MODULE_LIBRARY, so a symbol or module change shows up in the document.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { PinDef } from "../src/core/model.js";
import { cmpNatural } from "../src/geom/geom.js";
import { MODULE_LIBRARY } from "../src/modules/index.js";
import { BUILTIN } from "../src/symbols/library.js";

/** Keep a pin name safe inside a Markdown table cell and a code span. */function md(s: string): string {
  return s.replace(/`/g, "'").replace(/\|/g, "\\|");
}

function pinText(p: PinDef): string {
  let s = `\`${md(p.number)}\``;
  if (p.name !== p.number) s += ` (${md(p.name)}`;
  if (p.aliases !== undefined && p.aliases.length > 0) s += p.name === p.number ? ` (also ${p.aliases.map((a) => `\`${md(a)}\``).join(", ")})` : `; also ${p.aliases.map((a) => `\`${md(a)}\``).join(", ")})`;
  else if (p.name !== p.number) s += ")";
  return s;
}

interface Row {
  type: string;
  module: string;
  pins: string;
  groups: string;
}

function row(type: string, moduleName: string, pins: ReadonlyArray<PinDef>): Row {
  const groups = new Map<string, string[]>();
  for (const p of pins) {
    if (p.group === undefined) continue;
    const members = groups.get(p.group) ?? [];
    members.push(`\`${md(p.number)}\``);
    groups.set(p.group, members);
  }
  const groupText = [...groups.entries()]
    .map(([name, members]) => `\`${md(name)}\` (${members.join(", ")})`)
    .join("; ");
  return { type, module: moduleName, pins: pins.map(pinText).join(", "), groups: groupText };
}

const rows: Row[] = [];
for (const type of Object.keys(BUILTIN)) {
  const def = BUILTIN[type]!;
  rows.push(row(`\`${md(type)}\``, "", def.pins));
}
for (const [type, def] of Object.entries(MODULE_LIBRARY)) {
  rows.push(row(`\`${md(type)}\``, md(def.name), def.pins));
}
rows.sort((a, b) => cmpNatural(a.type, b.type));

const lines: string[] = [
  "Generated by npm run docs:parts. Do not edit by hand.",
  "",
  "# Part types",
  "",
  "Use these names for `type` in `circuit.parts[]`. A net endpoint names one pin:",
  "",
  "- `R1[1]` uses the pin number.",
  "- `D1.anode` uses the pin name or an alias after a dot.",
  "- `U1{GND}` uses a pin group, which joins every pin in that group.",
  "",
  "The Pins column gives each pin number in backticks, then its name, then any aliases.",
  "Two more types take their pins from the part itself, in its own `pins` list: `ic` (a chip",
  "drawn as a box) and `header` (a connector).",
  "",
  "| Type | Module | Pins | Groups |",
  "|---|---|---|---|",
];
for (const r of rows) lines.push(`| ${r.type} | ${r.module} | ${r.pins} | ${r.groups} |`);
lines.push("");

const out = fileURLToPath(new URL("../docs/parts.md", import.meta.url));
writeFileSync(out, `${lines.join("\n")}`, "utf8");
console.log(`wrote docs/parts.md (${rows.length} part types)`);
